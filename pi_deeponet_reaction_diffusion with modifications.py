import math

def taylor_sin_coefficients(A, B, N):
    coefficients = []
    for n in range(N):
        if n % 2 == 0:  # Only odd powers of x have non-zero coefficients
            coefficients.append(0)
        else:
            # Calculate the coefficient for x^n
            coeff = A * ((-1)**((n-1)//2)) * (B**n) / math.factorial(n)
            coefficients.append(coeff)

    return coefficients

def taylor_cos_coefficients(A, B, N):
    coefficients = []

    for n in range(N):
        if n % 2 == 1:  # Odd powers of x have zero coefficients
            coefficients.append(0)
        else:
            # Calculate the coefficient for x^n
            coeff = A * ((-1)**(n//2)) * (B**n) / math.factorial(n)
            coefficients.append(coeff)

    return coefficients

def taylor_exp_coefficients(A, B, N):
    coefficients = []

    for n in range(N):
        # Calculate the coefficient for x^n
        coeff = A * (B**n) / math.factorial(n)
        coefficients.append(coeff)

    return coefficients

def evaluate_taylor_series(coefficients, x_values):
    series_sum = np.zeros_like(x_values)
    for n, coeff in enumerate(coefficients):
        series_sum += coeff * (x_values**n)
    return series_sum


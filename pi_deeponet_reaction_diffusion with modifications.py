def fn(coefficients, x):
    """
    Evaluate the function value at each point in x using the provided Taylor series coefficients.

    :param coefficients: List of Taylor series coefficients
    :param x: A single value or a list of values at which to evaluate the function
    :return: A list of function values corresponding to each value in x
    """
    if isinstance(x, (int, float)):  # Check if x is a single value
        x = [x]  # Convert to list to handle uniformly

    function_values = []

    # Calculate the function value for each value in x
    for value in x:
        function_value = 0
        for n, coeff in enumerate(coefficients):
            function_value += coeff * (value ** n)
        function_values.append(function_value)

    return np.array(function_values)

def fn3(C, x):
    # Convert C to a TensorFlow tensor with shape (n, 6)
    C = tf.convert_to_tensor(C, dtype=tf.float32)

    # Convert x to a TensorFlow tensor
    x = tf.convert_to_tensor(x, dtype=tf.float32)

    # Expand dimensions of x to be compatible with C for broadcasting
    x_expanded = tf.expand_dims(x, axis=0)  # Shape (1, m) where m is the number of x values

    # Compute each term
    cos_term = C[:, 0:1] * tf.cos(C[:, 1:2] * x_expanded)
    sin_term = C[:, 2:3] * tf.sin(C[:, 3:4] * x_expanded)
    exp_term = C[:, 4:5] * tf.exp(C[:, 5:6] * x_expanded)

    # Sum the terms along the columns to get the result
    result = cos_term + sin_term + exp_term

    # Convert result to a numpy array and return
    return result.numpy()

def fn2(coefficients, x):
    """
    Evaluate the function value at x using the provided Taylor series coefficients.

    :param coefficients: List of Taylor series coefficients
    :param x: The point at which to evaluate the function
    :return: The function value at x
    """
    # Initialize the function value
    function_value = 0

    # Calculate the function value using the Taylor series
    for n, coeff in enumerate(coefficients):
        function_value += coeff * (x ** n)

    return function_value

